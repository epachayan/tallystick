"""Canonical three-party figures -> results/multihop.txt.

Regenerated by `make experiments`. Documents quote this file; the staleness
check recomputes the figures it states.
"""

from __future__ import annotations

import statistics
from pathlib import Path

from ..model.types import Outcome
from .boundary import classify, solved_both
from .conformance import EXPECTED_PREVENTED
from .generator import H_CLASSES, load_corpus
from .harness import reports
from .model import fmt
from .protocols import PROTOCOLS3

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "results" / "multihop.txt"

SHORT = {
    Outcome.CORRECT_BLAME: "blame",
    Outcome.CORRECT_CONTRADICTION: "contra",
    Outcome.CORRECT_ABSTAIN: "abstain",
    Outcome.MISSED: "MISSED",
    Outcome.FALSE_ACCUSATION: "FALSE-ACC",
    Outcome.OVER_ATTRIBUTION: "OVER-ATTR",
    Outcome.FALSE_CONTRADICTION: "FALSE-CON",
}


def facts(scs=None, reps=None) -> dict:
    """The numbers documents are allowed to quote, computed, never typed."""
    scs = scs or load_corpus()
    reps = reps or reports(scs)
    out = {"scenarios": len(scs), "classes": len(H_CLASSES), "protocols": len(PROTOCOLS3)}
    for name, (rep, loc, _d) in reps.items():
        out[f"{name}.full"] = rep.classes_fully_solved
        out[f"{name}.localised_full"] = sum(
            1 for h in H_CLASSES if loc.get(h, 0) == rep.per_class[h].n)
        out[f"{name}.false_contradiction"] = sum(
            c.counts.get(Outcome.FALSE_CONTRADICTION, 0) for c in rep.per_class.values())
        out[f"{name}.false_attribution"] = sum(c.false_attribution for c in rep.per_class.values())
    from .model import Truth3
    truths = {s["h_class"]: Truth3.from_scenario(s) for s in scs}
    out["localisable"] = sum(1 for h in H_CLASSES if truths[h].diverges)
    return out


def render() -> str:
    scs = load_corpus()
    reps = reports(scs)
    f = facts(scs, reps)
    L = []
    w = L.append
    w("=" * 100)
    w(f"THREE-PARTY FIGURES -- multihop.v0.1.jsonl, {f['scenarios']} three-party scenarios, "
      f"{f['classes']} H-classes, {f['protocols']} protocols")
    w("one intermediary (P -> I -> E); two-party corpus frozen (src/multihop/freeze.py)")
    w("=" * 100)
    w("")
    w("[per class] dominant outcome / instances localised (verdict names exactly D(w))")
    w("")
    w("  " + "class".ljust(7) + "D(w)".ljust(8)
      + "".join(n.ljust(17) for n in PROTOCOLS3))
    truths = {}
    from .model import Truth3
    for s in scs:
        truths.setdefault(s["h_class"], Truth3.from_scenario(s))
    for h in H_CLASSES:
        row = "  " + h.ljust(7) + fmt(truths[h].diverges).ljust(8)
        for name, (rep, loc, _d) in reps.items():
            c = rep.per_class[h]
            top = max(c.counts.items(), key=lambda kv: kv[1])[0]
            cell = f"{SHORT.get(top, top.value)} {loc.get(h, 0)}/{c.n}"
            if len(c.counts) > 1:
                cell += "*"
            row += cell.ljust(17)
        w(row)
    w("")
    w("  * mixed outcomes within the class")
    w("")
    w("[aggregate]")
    w("  " + "protocol".ljust(14) + "spec".ljust(10) + "full-class".ljust(12)
      + "localised".ljust(11) + "false-attr".ljust(12) + "false-contra".ljust(14)
      + "median bytes")
    for name, (rep, _loc, disc) in reps.items():
        w("  " + name.ljust(14) + PROTOCOLS3[name].spec_name.ljust(10)
          + f"{rep.classes_fully_solved}/{f['classes']}".ljust(12)
          + f"{f[name + '.localised_full']}/{f['localisable']}".ljust(11)
          + str(f[name + ".false_attribution"]).ljust(12)
          + str(f[name + ".false_contradiction"]).ljust(14)
          + str(int(statistics.median(disc))))
    w("")
    w("  full-class: every instance scored a success outcome. localised: every")
    w(f"  instance named exactly the diverging parties; out of the {f['localisable']} classes")
    w("  whose D(w) is non-empty, since an honest world has nothing to localise.")
    w("")
    w("[prevention] classes an honest receiver refuses before the out-of-delegation action")
    for n, v in EXPECTED_PREVENTED.items():
        w(f"  {n:<9} {', '.join(sorted(v)) or 'none'}")
    w("")
    w("[boundary] derived twin pairs")
    w("  " + "pair".ljust(8) + "D(a)".ljust(9) + "D(b)".ljust(9) + "twin under".ljust(22)
      + "brute".ljust(8) + "D&D rule".ljust(10) + "D==D rule".ljust(11) + "solved both by")
    for a, b, protos, brute, inter, eq, da, db in classify(scs):
        specs = ",".join(sorted({PROTOCOLS3[n].spec_name for n in protos}))
        both = solved_both(scs, reps, a, b, protos)
        w("  " + f"{a}/{b}".ljust(8) + fmt(da).ljust(9) + fmt(db).ljust(9) + specs.ljust(22)
          + ("esc" if brute else "binds").ljust(8) + ("esc" if inter else "binds").ljust(10)
          + ("esc" if eq else "binds").ljust(11) + (", ".join(both) or "-"))
    w("")
    return "\n".join(L) + "\n"


def main():
    text = render()
    OUT.write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
